package com.shopsmart.rag;

import com.shopsmart.exception.ApiException;
import lombok.extern.slf4j.Slf4j;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.core.annotation.Order;
import org.springframework.http.HttpStatus;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;
import java.util.List;

/**
 * Creates the pgvector extension and policy_documents at startup. The vector dimension comes from configuration
 * (it must match the embedding model). If pgvector is missing the app still starts; only the RAG endpoints answer 503.
 * If an EMPTY policy_documents table has the wrong shape or dimension it is recreated automatically.
 */
@Component
@Order(1)
@Slf4j
public class RagSchemaInitializer implements ApplicationRunner {
    private final JdbcTemplate jdbc;
    private final int dim;
    private final String apiKey;
    private volatile String problem = "RAG schema has not been initialised yet";

    public RagSchemaInitializer(JdbcTemplate jdbc, @Value("${app.rag.embedding-dimension}") int dim,
                                @Value("${spring.ai.openai.api-key}") String apiKey) {
        this.jdbc = jdbc;
        this.dim = dim;
        this.apiKey = apiKey;
    }

    /** null when RAG storage is ready, otherwise a human-readable reason. */
    public String problem() { return problem; }

    private String createSql() {
        // dim is an int from configuration, so concatenating it is safe
        return "CREATE TABLE IF NOT EXISTS policy_documents ("
                + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                + "document_id BIGINT NOT NULL REFERENCES documents(id) ON DELETE CASCADE,"
                + "content TEXT NOT NULL,"
                + "chunk_index INTEGER NOT NULL,"
                + "embedding vector(" + dim + ") NOT NULL,"
                + "metadata JSONB NOT NULL DEFAULT '{}'::jsonb,"
                + "created_at TIMESTAMPTZ NOT NULL DEFAULT now())";
    }

    @Override
    public void run(ApplicationArguments args) {
        if (apiKey == null || apiKey.isBlank() || "not-configured".equals(apiKey)) {
            log.warn("GEMINI_API_KEY is not set: AI recommendations, document indexing and policy Q&A will fail until you set it.");
        }
        try {
            try {
                jdbc.execute("CREATE EXTENSION IF NOT EXISTS vector");
            } catch (Exception e) {
                problem = "pgvector is not installed in this PostgreSQL server (see README, 'Install pgvector')";
                log.warn("RAG disabled: {}", problem);
                return;
            }
            jdbc.execute(createSql());

            Integer cols = jdbc.queryForObject("SELECT count(*) FROM information_schema.columns "
                    + "WHERE table_schema = current_schema() AND table_name = 'policy_documents' "
                    + "AND column_name IN ('document_id','content','chunk_index','embedding','metadata')", Integer.class);
            List<Integer> mods = jdbc.queryForList("SELECT atttypmod FROM pg_attribute "
                    + "WHERE attrelid = 'policy_documents'::regclass AND attname = 'embedding'", Integer.class);
            boolean ok = cols != null && cols == 5 && !mods.isEmpty() && mods.get(0) == dim;
            if (!ok) {
                Integer rows = null;
                try { rows = jdbc.queryForObject("SELECT count(*) FROM policy_documents", Integer.class); } catch (Exception ignored) { }
                if (rows != null && rows == 0) {
                    jdbc.execute("DROP TABLE policy_documents");
                    jdbc.execute(createSql());
                    log.warn("policy_documents was empty but had the wrong columns or dimension; recreated as vector({})", dim);
                } else {
                    problem = "policy_documents does not match EMBEDDING_DIMENSION=" + dim
                            + ". Run in psql/pgAdmin: DROP TABLE policy_documents; DELETE FROM documents; then restart.";
                    log.warn("RAG disabled: {}", problem);
                    return;
                }
            }
            jdbc.execute("CREATE INDEX IF NOT EXISTS idx_policy_documents_document ON policy_documents(document_id)");
            try { // HNSW needs pgvector 0.5+; without it, search still works (sequential scan)
                jdbc.execute("CREATE INDEX IF NOT EXISTS idx_policy_documents_embedding "
                        + "ON policy_documents USING hnsw (embedding vector_cosine_ops)");
            } catch (Exception e) {
                log.warn("Could not create HNSW index (old pgvector?); continuing without it: {}", e.getMessage());
            }
            jdbc.update("UPDATE documents SET status = 'FAILED', status_message = 'Interrupted by server restart', "
                    + "updated_at = now() WHERE status = 'PROCESSING'");
            problem = null;
            log.info("RAG ready (vector({}))", dim);
        } catch (Exception e) {
            problem = "RAG schema setup failed (see server log)";
            log.error("RAG schema setup failed", e);
        }
    }

    public void requireReady() {
        if (problem != null) throw new ApiException(HttpStatus.SERVICE_UNAVAILABLE, "RAG_UNAVAILABLE", problem);
    }
}
